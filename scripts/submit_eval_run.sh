#!/bin/bash
#SBATCH --job-name=eval_run
#SBATCH --partition=gpu
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=1
#SBATCH --gres=gpu:1
#SBATCH --mem=16G
#SBATCH --time=02:00:00
#SBATCH --output=logs/eval_run_%j.out
#SBATCH --error=logs/eval_run_%j.err

# Generic CFM evaluation wrapper. Generates an eval config on the fly that
# points at one trained CFM output dir + the matching summary directory, then
# runs src/evaluation/sample.py and src/evaluation/plotting.py.
#
# Usage:
#   sbatch --export=MODEL_DIR=<path>,SUMMARY_DIR=<path>[,NUM_SAMPLES=500] \
#          submit_eval_run.sh
#
# MODEL_DIR is a CFM output directory containing best_cfm_model.pth +
# target_norm_stats.npz + cond_norm_stats.npz + test_indices.npy.
# SUMMARY_DIR is the loreli_summaries_* directory used during training.

# See submit_scaling_cfm.sh for the rationale on -eo pipefail (no -u).
set -eo pipefail

if [[ -z "${MODEL_DIR:-}" || -z "${SUMMARY_DIR:-}" ]]; then
    echo "ERROR: must export MODEL_DIR and SUMMARY_DIR before sbatch" >&2
    echo "  sbatch --export=MODEL_DIR=...,SUMMARY_DIR=... submit_eval_run.sh" >&2
    exit 1
fi

NUM_SAMPLES="${NUM_SAMPLES:-500}"

echo "=================================================="
echo "Eval run"
echo "  MODEL_DIR   = $MODEL_DIR"
echo "  SUMMARY_DIR = $SUMMARY_DIR"
echo "  NUM_SAMPLES = $NUM_SAMPLES"
echo "  Job=$SLURM_JOB_ID  Node=$SLURMD_NODENAME"
echo "  Time=$(date)"
echo "=================================================="

module load mpi/openmpi/4.1-gnu-14.2
module load devel/miniforge
conda activate eor_env

cd /pfs/10/work/hd_pt254-skatr/EoRFlow-dev
mkdir -p scripts/logs configs_auto

# Sanity checks
for f in best_cfm_model.pth target_norm_stats.npz cond_norm_stats.npz test_indices.npy; do
    if [[ ! -f "$MODEL_DIR/$f" ]]; then
        echo "ERROR: $MODEL_DIR is missing $f" >&2
        exit 1
    fi
done
if [[ ! -d "$SUMMARY_DIR" ]]; then
    echo "ERROR: SUMMARY_DIR $SUMMARY_DIR does not exist" >&2
    exit 1
fi

# Generate per-run eval YAML. The format mirrors config/eval_skatr_loreli_trial.yaml.
RUN_TAG=$(basename "$MODEL_DIR")
CFG="configs_auto/eval_${RUN_TAG}_${SLURM_JOB_ID}.yaml"

cat > "$CFG" <<YAML
# Auto-generated by submit_eval_run.sh for $RUN_TAG
mode: skatr
data: loreli
inference: cfm

data_type: skatr
learn_target: sim_params

param_names:
  - \$f_x\$
  - \$\\tau\$
  - \$r_H\$
  - \$\\log M_{\\min}\$
  - \$f_{\\mathrm{esc,post}}\$

project_root: /pfs/10/work/hd_pt254-skatr/EoRFlow-dev
output_subpath: output
database_subpath: database

model_path: ${MODEL_DIR}/best_cfm_model.pth
test_indices_path: ${MODEL_DIR}/test_indices.npy

skatr:
  source: loreli
  source_dirs:
    loreli: ${SUMMARY_DIR}
  sim_param_indices: null
  drop_tvir: false
  num_sim_params: 5
  normalize_cond: false
  cond_normalization: zscore
  cond_norm_stats_path: ${MODEL_DIR}/cond_norm_stats.npz
  target_norm_stats_path: ${MODEL_DIR}/target_norm_stats.npz

num_samples_per_sim: ${NUM_SAMPLES}
num_sims: null
batch_size: 16
seed: 42

min_redshift_index: 3
max_redshift_index: 15
YAML

echo "Wrote auto-config: $CFG"
echo ""
echo "Running sampling..."
python src/evaluation/sample.py --config "$CFG"

SAMPLES_FILE="${MODEL_DIR}/samples.npz"
if [[ ! -f "$SAMPLES_FILE" ]]; then
    echo "ERROR: samples file not produced at $SAMPLES_FILE" >&2
    exit 1
fi

echo ""
echo "Running diagnostic plots..."
python src/evaluation/plotting.py --samples "$SAMPLES_FILE" --n_panels 5

echo ""
echo "Done. samples.npz at $SAMPLES_FILE"
echo "End time: $(date)"
